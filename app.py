import pandas as pd

danh_sach_sv = {
    "Ho_ten": [
        "Nguyễn Văn An", "Trần Thị Bích", "Lê Hoàng Cường",
        "Phạm Thị Dung", "Hoàng Văn Em", "Đỗ Thị Phương",
        "Bùi Văn Giang", "Vũ Thị Hương", "Ngô Văn Khải", "Phan Thị Lan"
    ],
    "Chuyen_can": [9.0, 8.0, 7.5, 6.0, 8.5, 9.5, 4.0, 7.0, 8.0, 5.5],
    "Giua_ky": [8.0, 7.5, 6.5, 5.0, 7.0, 9.0, 4.5, 6.5, 8.5, 6.0],
    "Cuoi_ky": [8.5, 8.0, 7.0, 5.5, 7.5, 8.5, 3.5, 6.5, 9.0, 5.0]
}

bang_diem = pd.DataFrame(danh_sach_sv)
display(bang_diem)

bang_diem["Tong_ket"] = bang_diem.eval("Chuyen_can * 0.2 + Giua_ky * 0.3 + Cuoi_ky * 0.5").round(2)
display(bang_diem)

def phan_loai(diem_tk):
    if diem_tk < 5.0:
        return "Yếu"
    elif diem_tk < 7.0:
        return "Trung bình"
    elif diem_tk < 8.5:
        return "Khá"
    else:
        return "Giỏi"

bang_diem["Xep_loai"] = bang_diem["Tong_ket"].map(phan_loai)
display(bang_diem)

tb_chung = bang_diem["Tong_ket"].mean()
sv_max = bang_diem.nlargest(1, "Tong_ket").iloc[0]
sv_min = bang_diem.nsmallest(1, "Tong_ket").iloc[0]
sl_dat = (bang_diem["Tong_ket"] >= 5.0).sum()

print("--- THỐNG KÊ KẾT QUẢ ---")
print(f"Điểm trung bình toàn lớp: {tb_chung:.2f}")
print(f"Điểm cao nhất thuộc về: {sv_max['Ho_ten']} ({sv_max['Tong_ket']})")
print(f"Điểm thấp nhất thuộc về: {sv_min['Ho_ten']} ({sv_min['Tong_ket']})")
print(f"Tổng số sinh viên đạt yêu cầu: {sl_dat}")

import matplotlib.pyplot as plt

fig, ax = plt.subplots(figsize=(10, 5))
ax.bar(bang_diem["Ho_ten"], bang_diem["Tong_ket"], color="teal", edgecolor="black")
ax.set_xlabel("Sinh viên", fontsize=12)
ax.set_ylabel("Tổng kết", fontsize=12)
ax.set_title("Biểu đồ điểm tổng kết sinh viên", fontsize=14, fontweight="bold")
plt.xticks(rotation=45, ha="right")
plt.tight_layout()
plt.show()

print("Người thực hiện: Trần Nguyễn Trung Hậu")

